package basic;

public class datatypes {
    public static void main(String[] args) {
        byte age = 20;
        short year = 2026;
        int population = 1400000000;
        long distance = 12345678900L;
        float height = 178.5f;
        double price = 99999.99;
        char grade = 'A';
        boolean isStudent = true;
        // Printing the above   values
        System.out.println("byte: " + age);
        System.out.println("short: " + year);
        System.out.println("int: " + population);
        System.out.println("long: " + distance);
        System.out.println("float: " + height);
        System.out.println("double: " + price);
        System.out.println("char: " + grade);
        System.out.println("boolean: " + isStudent);
    }

}
